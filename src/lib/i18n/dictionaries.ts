export const dictionaries = { "pt-BR": pt as Dictionary, en } as const;

export function translate(dict: Dictionary, key: DictKey, vars?: Record<string, string | number>) {
  let s = dict[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

export function errorKey(code: string): DictKey {
  const k = `error.${code}` as DictKey;
  return k in pt ? k : "error.generic";
}
